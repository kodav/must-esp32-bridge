#pragma once
#include <Arduino.h>
#include <functional>

// Persist-история во флеш (LittleFS) -- переживает перезагрузку/
// перепрошивку, в отличие от PSRAM-буфера (history.cpp), который
// каждый раз стартует с нуля.
//
// ПРИНЦИПИАЛЬНО ДРУГАЯ модель записи: PSRAM-буфер пишет КАЖДОЕ чтение
// (это нормально для RAM), но такая частота записи убила бы флеш по
// циклам стирания (~28 тысяч записей/час при 79 регистрах и 10с
// опросе). Вместо этого сюда пишутся периодические "снимки" -- раз в
// несколько минут одним пакетом сохраняются последние известные
// значения всех регистров разом. Даёт более грубую, но переживающую
// перезагрузку историю (по умолчанию ~5 минут между точками).
//
// Кольцевой файл фиксированного размера на разделе LittleFS (тот же,
// что и config.json) -- при заполнении новые снимки затирают самые
// старые, файл не растёт бесконечно.

void historyFlashSetup();

// Вызывать на каждое чтение (как historyPush()) -- просто обновляет
// "последнее известное значение" в памяти, реальная запись во флеш
// происходит только по таймеру внутри historyFlashLoop().
void historyFlashPush(const String &name, float value);

// Вызывать каждую итерацию main loop() -- проверяет, не пора ли писать
// очередной снимок во флеш (раз в flash_history_interval_min минут).
void historyFlashLoop();

// Пересоздать файл под новые параметры (список регистров, интервал) --
// вызывать после сохранения конфига, как historyReconfigure().
void historyFlashReconfigure();

// Потоковый экспорт всех сохранённых снимков в CSV (тот же формат, что
// historyExportCsv(): timestamp,register,value).
void historyFlashExportCsv(const std::function<void(const String &)> &onChunk);
