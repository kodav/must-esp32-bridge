#pragma once
#include <Arduino.h>

// RGB-индикатор состояния устройства (WS2812/NeoPixel, обычно один пиксель
// на плате). Приоритет состояний (сверху вниз, самое важное побеждает):
//
//   OTA идёт          -> фиолетовый, быстрая пульсация  -- "не трогай, не выключай"
//   AP-режим (настройка) -> жёлтый, быстрое мигание      -- "зайди и настрой WiFi"
//   WiFi подключается -> синий, мигание
//   MQTT не подключен  -> оранжевый, мигание             -- WiFi есть, брокер недоступен
//   Инвертор не отвечает -> красный, мигание             -- RS485 не даёт данных
//   Всё в порядке      -> зелёный, ровно (редкий "вдох" раз в несколько секунд)
//
// Логика состояния вычисляется автоматически из WiFi.status(),
// mqttIsConnected() и modbusIsHealthy() -- вызывающему коду достаточно
// один раз в setup() позвать statusLedSetup(), а в loop() -- statusLedLoop().

void statusLedSetup();
void statusLedLoop();

// Дёргать из колбэков ElegantOTA (onStart/onEnd), чтобы подсветить процесс апдейта.
void statusLedSetOtaActive(bool active);

// Вызывается из main.cpp сразу после решения "подключились к WiFi" или
// "подняли точку доступа для настройки" -- индикатору неоткуда узнать
// это самому, WiFi.status() не отличает "AP-режим" от прочего.
void statusLedSetApMode(bool apMode);
