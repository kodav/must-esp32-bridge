#pragma once
#include <Arduino.h>
#include <functional>

// Локальная история показаний -- кольцевой буфер в PSRAM, живёт
// независимо от MQTT/WiFi (в отличие от старой идеи "офлайн-буфер для
// MQTT", эта версия просто НИКУДА не отправляется сама, а служит для
// просмотра прямо в веб-интерфейсе устройства: таблица + график).

void historySetup();

// Вызывать на каждое успешно прочитанное значение регистра (из того же
// колбэка modbusPollLoop(), что уже вызывает mqttPublishValue()).
void historyPush(const String &name, float value);

// Пересоздать буфер под новые параметры конфига (число регистров,
// poll_interval_ms, history_hours) -- вызывать после сохранения конфига.
void historyReconfigure();

// JSON вида {"points":[{"t":1721300000,"v":231.4}, ...]} -- до maxPoints
// точек, равномерно прорежённых по всей доступной истории для этого
// регистра. t -- unix-время (секунды), если NTP ещё не синхронизировался
// на момент записи -- будет использовано приблизительное время на основе
// millis() (это будет видно по неправдоподобно раннему году в t).
String historyGetJson(const String &registerName, size_t maxPoints);

// Потоковый экспорт ВСЕГО накопленного буфера (все регистры, без
// прореживания) в CSV -- вызывает onChunk() пачками по ~4KB текста,
// чтобы не собирать весь CSV одной гигантской строкой в памяти (при
// глубокой истории записей может быть больше миллиона). Формат
// "длинный": timestamp,register,value по одной строке на запись --
// проще пивотить в Excel/pandas при необходимости, чем городить широкий
// формат с колонкой на регистр (разные регистры опрашиваются в разные
// моменты, выровнять по времени 1:1 всё равно не получится честно).
void historyExportCsv(const std::function<void(const String &)> &onChunk);
